def mark(results: list[dict]) -> str:
    """'2/3' style cell for one case and one system, with failed check names."""
    cell = f"{sum(r['passed'] for r in results)}/{len(results)}"
    failed = sorted({name for r in results for name, ok in r["checks"].items() if not ok})
    errors = sum(r["error"] is not None for r in results)
    notes = [f"missed: {', '.join(failed)}"] if failed else []
    notes += [f"{errors} crashed"] if errors else []
    return cell + (f" ({'; '.join(notes)})" if notes else "")


def render_results(cases: list[Case], runs: dict, repeats: int, model: str) -> str:
    lines = [
        "# Eval results", "",
        f"Date: {date.today()} · Model: `{model}` · Cases: {len(cases)} · Runs per case: {repeats}", "",
        "Generated by `python -m eval.run_eval`. Scoring is automatic (see `eval/cases.py`): a run",
        "passes only if every keyword and number check passes. Raw answers are in `eval/outputs/`.", "",
        "## Summary", "",
        "| System | Runs passed | Checks passed | Avg seconds per run | Avg input tokens | Avg output tokens |",
        "|---|---|---|---|---|---|",
    ]
    for system in SYSTEMS:
        rs = [r for c in cases for r in runs[c.id][system]]
        checks = [ok for r in rs for ok in r["checks"].values()]
        avg = lambda xs: round(sum(xs) / len(xs)) if xs else 0  # noqa: E731
        lines.append(
            f"| {system} | {sum(r['passed'] for r in rs)}/{len(rs)} | {sum(checks)}/{len(checks)} "
            f"| {sum(r['seconds'] for r in rs) / len(rs):.1f} "
            f"| {avg([r['tokens']['input_tokens'] for r in rs])} "
            f"| {avg([r['tokens']['output_tokens'] for r in rs])} |")

    lines += ["", "## Per case", "", "| Case | Question | Pipeline | Baseline |", "|---|---|---|---|"]
    for c in cases:
        lines.append(f"| {c.id} | {c.question} | {mark(runs[c.id]['pipeline'])} | {mark(runs[c.id]['baseline'])} |")

    pipe = [r for c in cases for r in runs[c.id]["pipeline"] if r["error"] is None]
    if pipe:
        lines += ["", "## Pipeline internals", "",
                  f"- Critic approved the final report in {sum(r['critic_approved'] for r in pipe)}/{len(pipe)} runs.",
                  f"- Analysis steps that succeeded: {sum(r['steps_ok'] for r in pipe)}/"
                  f"{sum(r['steps_total'] for r in pipe)}."]
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description="Evaluate the pipeline against a single-LLM baseline")
    parser.add_argument("--repeats", type=int, default=1)
    parser.add_argument("--cases", nargs="*", help="case ids to run (default: all)")
    args = parser.parse_args()

    cases = [c for c in CASES if not args.cases or c.id in args.cases]
    if not cases:
        print(f"No matching cases. Known: {[c.id for c in CASES]}", file=sys.stderr)
        return 1

    load_dotenv()
    ensure_datasets()
    llm = LLM()
    runs = {c.id: {s: [] for s in SYSTEMS} for c in cases}
    for c in cases:
        for n in range(1, args.repeats + 1):
            for system in SYSTEMS:
                print(f"{c.id} / {system} / run {n} ...", end=" ", flush=True)
                result = run_one(system, c, llm)
                runs[c.id][system].append(result)
                save_answer(c, system, n, result)
                print("PASS" if result["passed"] else "FAIL", f"({result['seconds']}s)")

    (EVAL_DIR / "results.md").write_text(
        render_results(cases, runs, args.repeats, os.environ.get("MODEL_NAME", "?")), encoding="utf-8")
    print(f"Wrote {EVAL_DIR / 'results.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
