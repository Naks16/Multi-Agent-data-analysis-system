"""Run every eval case through the agent pipeline and the single-LLM baseline.

    python -m eval.run_eval                 # all cases, both systems, 1 run each
    python -m eval.run_eval --repeats 3     # LLM answers vary, so repeats give a fairer picture
    python -m eval.run_eval --cases churn_by_plan top_aov

Writes eval/results.md (tables) and eval/outputs/<case>__<system>__<n>.md (each raw answer,
so a human can check the automatic scoring).
"""

import argparse
import json
import os
import sys
import time
from datetime import date
from pathlib import Path

import anthropic
from dotenv import load_dotenv

from analyst.graph import run_analysis
from analyst.llm import LLM, LLMJsonError
from eval.baseline import run_baseline
from eval.cases import CASES, Case, score
from eval.datasets import ensure_datasets

EVAL_DIR = Path(__file__).parent
OUTPUT_DIR = EVAL_DIR / "outputs"
SYSTEMS = ("pipeline", "baseline")


def answer_part(report: str) -> str:
    """The part of report.md that answers the question: Short answer, Key findings and
    Statistical tests. Charts, Limitations and reviewer caveats are left out of scoring."""
    start = report.find("## Short answer")
    ends = [i for i in (report.find("## Charts"), report.find("## Limitations")) if i != -1]
    return report[start:min(ends)] if ends else report[start:]


def trace_tokens(run_dir: str) -> dict:
    total = {"input_tokens": 0, "output_tokens": 0}
    with open(Path(run_dir) / "trace.jsonl", encoding="utf-8") as f:
        for line in f:
            for key, n in json.loads(line).get("tokens", {}).items():
                total[key] += n
    return total


def run_one(system: str, case: Case, llm: LLM) -> dict:
    """Run one system on one case. Never raises: a crash counts as a failed case."""
    start = time.perf_counter()
    result = {"answer": "", "tokens": {"input_tokens": 0, "output_tokens": 0}, "error": None}
    try:
        if system == "pipeline":
            final = run_analysis(case.csv, case.question, llm)
            result["answer"] = answer_part(final["report"])
            result["tokens"] = trace_tokens(final["run_dir"])
            result["critic_approved"] = final["critic_feedback"]["approved"]
            result["steps_ok"] = sum(r["success"] for r in final["step_results"])
            result["steps_total"] = len(final["step_results"])
        else:
            result["answer"], result["tokens"] = run_baseline(case.csv, case.question, llm)
    except (LLMJsonError, RuntimeError, anthropic.APIError) as e:
        result["error"] = f"{type(e).__name__}: {e}"
    result["seconds"] = round(time.perf_counter() - start, 1)
    result["checks"] = score(case, result["answer"])
    result["passed"] = result["error"] is None and all(result["checks"].values())
    return result


def save_answer(case: Case, system: str, n: int, result: dict) -> None:
    OUTPUT_DIR.mkdir(exist_ok=True)
    checks = "\n".join(f"- {'PASS' if ok else 'FAIL'}: {name}" for name, ok in result["checks"].items())
    body = result["answer"] or f"(no answer - {result['error']})"
    (OUTPUT_DIR / f"{case.id}__{system}__{n}.md").write_text(
        f"# {case.id} / {system} / run {n}\n\n**Question:** {case.question}\n\n"
        f"## Checks\n\n{checks}\n\n## Answer\n\n{body}\n", encoding="utf-8")


